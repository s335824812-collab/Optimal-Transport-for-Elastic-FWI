def plot_landscape_slices(res: dict):
    """
    Figure 4.2: one-dimensional slices through the landscapes.

    The legend is shared by the two panels and placed above the axes,
    matching the style used by the other profile figures in the paper.
    """
    ip0 = nearest_index(
        res["phis"],
        0.0,
    )

    it0 = nearest_index(
        res["taus"],
        0.0,
    )

    J_l2_n = normalize01(
        res["J_l2"]
    )
    J_cot_n = normalize01(
        res["J_cot"]
    )
    J_rot_n = normalize01(
        res["J_rot"]
    )

    # Do not use constrained_layout here: reserve an explicit top margin
    # for a figure-level legend, consistent with the other manuscript plots.
    fig, axes = plt.subplots(
        1,
        2,
        figsize=(8.8, 3.6),
    )

    # --------------------------------------------------------
    # (a) Time-shift slice, phi = 0
    # --------------------------------------------------------
    axes[0].plot(
        res["taus"],
        J_l2_n[ip0, :],
        label=r"$L^2$",
    )
    axes[0].plot(
        res["taus"],
        J_cot_n[ip0, :],
        label="COT",
    )
    axes[0].plot(
        res["taus"],
        J_rot_n[ip0, :],
        label="ROT",
    )

    axes[0].set_title(
        r"$\varphi=0$",
        fontsize=12,
        pad=5,
    )
    axes[0].set_xlabel(
        r"Time shift $\tau$ (s)",
        fontsize=10,
    )
    axes[0].set_ylabel(
        "Normalized misfit",
        fontsize=10,
    )

    axes[0].grid(
        alpha=0.25,
    )

    add_panel_label(
        axes[0],
        "(a)",
    )

    # --------------------------------------------------------
    # (b) Rotation slice, tau = 0
    # --------------------------------------------------------
    axes[1].plot(
        res["phis"],
        J_l2_n[:, it0],
        label=r"$L^2$",
    )
    axes[1].plot(
        res["phis"],
        J_cot_n[:, it0],
        label="COT",
    )
    axes[1].plot(
        res["phis"],
        J_rot_n[:, it0],
        label="ROT",
    )

    axes[1].set_title(
        r"$\tau=0$",
        fontsize=12,
        pad=5,
    )
    axes[1].set_xlabel(
        r"Rotation angle $\varphi$",
        fontsize=10,
    )

    set_standard_angle_ticks(
        axes[1],
        axis="x",
    )

    # Same y quantity in both panels; keep the ticks but omit the repeated label.
    axes[1].set_ylabel("")
    axes[1].grid(
        alpha=0.25,
    )

    add_panel_label(
        axes[1],
        "(b)",
    )

    # Shared legend above both panels, matching Figs. 4.4--4.7:
    # horizontal, centered, and without a surrounding frame.
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="upper center",
        bbox_to_anchor=(0.5, 0.985),
        ncol=3,
        frameon=False,
        fontsize=9,
        handlelength=2.2,
        handletextpad=0.5,
        columnspacing=1.5,
    )

    # Leave space between the legend and the two axes.
    fig.subplots_adjust(
        left=0.09,
        right=0.98,
        bottom=0.17,
        top=0.82,
        wspace=0.22,
    )

    path = OUT_DIR / "figure_landscape_slices.png"

    fig.savefig(
        path,
        dpi=DPI,
        bbox_inches="tight",
    )
    plt.close(fig)

    print(f"[saved] {path}")


