# Figure 2: landscape comparison
# ============================================================

def plot_landscape_comparison(res: dict):
    """
    Figure 4.1: heatmap comparison of the normalized landscapes.

    Each landscape is independently normalized to [0, 1].
    The explicit minimum marker is intentionally omitted to keep
    the figure visually clean.
    """
    arrays = [
        normalize01(res["J_l2"]),
        normalize01(res["J_cot"]),
        normalize01(res["J_rot"]),
    ]

    titles = [
        r"$L^2$",
        "COT",
        "ROT",
    ]

    panel_labels = [
        "(a)",
        "(b)",
        "(c)",
    ]

    extent = [
        res["taus"][0],
        res["taus"][-1],
        res["phis"][0],
        res["phis"][-1],
    ]

    fig, axes = plt.subplots(
        1,
        3,
        figsize=(11.5, 3.7),
        sharey=True,
        constrained_layout=True,
    )

    im = None

    for i, (ax, A, title, plabel) in enumerate(
        zip(axes, arrays, titles, panel_labels)
    ):
        im = ax.imshow(
            A,
            origin="lower",
            aspect="auto",
            extent=extent,
            cmap=CMAP,
            vmin=0.0,
            vmax=1.0,
        )

        # Guide lines through the exact alignment (tau, phi) = (0, 0).
        ax.axvline(
            0.0,
            linewidth=0.7,
            alpha=0.5,
        )
        ax.axhline(
            0.0,
            linewidth=0.7,
            alpha=0.5,
        )

        ax.set_title(
            title,
            fontsize=12,
        )

        ax.set_xlabel(
            r"Time shift $\tau$ (s)",
            fontsize=10,
        )

        if i == 0:
            ax.set_ylabel(
                r"Rotation angle $\varphi$",
                fontsize=10,
            )
            set_standard_angle_ticks(
                ax,
                axis="y",
            )

        add_panel_label(
            ax,
            plabel,
        )

    cbar = fig.colorbar(
        im,
        ax=axes,
        shrink=0.96,
        pad=0.02,
    )
    cbar.set_label(
        "Normalized misfit",
        fontsize=10,
    )

    path = OUT_DIR / "figure_landscape_comparison.png"

    fig.savefig(
        path,
        dpi=DPI,
        bbox_inches="tight",
    )
    plt.close(fig)

    print(f"[saved] {path}")


