def plot_3d_example(res: dict):
    x = res["x"]
    u = res["u"]

    d_demo = transform_signal(
        u,
        x,
        TAU_DEMO,
        PHI_DEMO,
    )

    fig = plt.figure(
        figsize=(9.0, 4.8),
    )

    ax = fig.add_subplot(
        111,
        projection="3d",
    )

    ax.plot(
        x,
        u[0],
        u[1],
        linewidth=2.2,
        label="Reference",
    )

    ax.plot(
        x,
        d_demo[0],
        d_demo[1],
        linewidth=2.2,
        label="Shifted + rotated",
    )

    idx_u = int(
        np.argmax(
            np.linalg.norm(u, axis=0)
        )
    )

    idx_d = int(
        np.argmax(
            np.linalg.norm(d_demo, axis=0)
        )
    )

    ax.scatter(
        [x[idx_u]],
        [u[0, idx_u]],
        [u[1, idx_u]],
        s=35,
    )

    ax.scatter(
        [x[idx_d]],
        [d_demo[0, idx_d]],
        [d_demo[1, idx_d]],
        s=35,
    )

    # Crop to the informative part of the waveform
    ax.set_xlim(
        DEMO_T_MIN,
        DEMO_T_MAX,
    )

    mask = (
        (x >= DEMO_T_MIN)
        & (x <= DEMO_T_MAX)
    )

    xcomp_show = np.concatenate(
        [
            u[0, mask],
            d_demo[0, mask],
        ]
    )

    zcomp_show = np.concatenate(
        [
            u[1, mask],
            d_demo[1, mask],
        ]
    )

    dx_amp = max(
        xcomp_show.max()
        - xcomp_show.min(),
        1.0e-12,
    )

    dz_amp = max(
        zcomp_show.max()
        - zcomp_show.min(),
        1.0e-12,
    )

    ax.set_ylim(
        xcomp_show.min() - 0.08 * dx_amp,
        xcomp_show.max() + 0.08 * dx_amp,
    )

    ax.set_zlim(
        zcomp_show.min() - 0.08 * dz_amp,
        zcomp_show.max() + 0.08 * dz_amp,
    )

    ax.set_xlabel(
        "Time (s)",
        labelpad=8,
    )
    ax.set_ylabel(
        r"$u_x$",
        labelpad=10,
    )
    ax.set_zlabel(
        r"$u_z$",
        labelpad=8,
    )

    ax.set_title(
        r"Time shift and planar rotation",
        pad=12,
        fontsize=15,
    )

    ax.view_init(
        elev=18,
        azim=-68,
    )

    try:
        ax.set_box_aspect(
            (4.8, 1.8, 1.8),
            zoom=1.25,
        )
    except TypeError:
        ax.set_box_aspect(
            (4.8, 1.8, 1.8)
        )

    # Legend stays below the title.
    ax.legend(
        loc="upper center",
        bbox_to_anchor=(0.5, 0.90),
        ncol=2,
        fontsize=9,
        frameon=True,
    )

    # Move transformation parameters away from title/legend.
    ax.text2D(
        0.04,
        0.76,
        r"$\tau=0.10\,\mathrm{s},\ \varphi=\pi/4$",
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=10,
        bbox=dict(
            boxstyle="round,pad=0.22",
            facecolor="white",
            alpha=0.80,
            edgecolor="none",
        ),
    )

    path = OUT_DIR / "figure_3d_example.png"

    fig.savefig(
        path,
        dpi=DPI,
        bbox_inches="tight",
    )
    plt.close(fig)

    print(f"[saved] {path}")


