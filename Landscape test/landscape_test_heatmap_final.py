# ============================================================
# Signal construction
# ============================================================

def ricker(t: np.ndarray, f0: float, t0: float) -> np.ndarray:
    a = np.pi * f0 * (t - t0)
    return (1.0 - 2.0 * a**2) * np.exp(-a**2)


def build_reference_signal(t: np.ndarray) -> np.ndarray:
    """
    u(t) = p r(t),
    p = (cos(theta0), sin(theta0))^T.
    """
    w = AMPLITUDE * ricker(t, F0, T0)

    p = np.array(
        [
            np.cos(POLARIZATION_ANGLE),
            np.sin(POLARIZATION_ANGLE),
        ],
        dtype=np.float64,
    )

    return p[:, None] * w[None, :]


def rotation_matrix(phi: float) -> np.ndarray:
    c = np.cos(phi)
    s = np.sin(phi)

    return np.array(
        [
            [c, -s],
            [s,  c],
        ],
        dtype=np.float64,
    )


def shift_signal(
    u: np.ndarray,
    t: np.ndarray,
    tau: float,
) -> np.ndarray:
    """Evaluate u(t-tau) by linear interpolation."""
    query = t - tau
    out = np.empty_like(u)

    for k in range(2):
        out[k] = np.interp(
            query,
            t,
            u[k],
            left=0.0,
            right=0.0,
        )

    return out


def transform_signal(
    u: np.ndarray,
    t: np.ndarray,
    tau: float,
    phi: float,
) -> np.ndarray:
    """
    d_{tau,phi}(t) = Q_phi u(t-tau).
    """
    return rotation_matrix(phi) @ shift_signal(u, t, tau)


# ============================================================
# Misfits
# ============================================================

def l2_misfit(
    u: np.ndarray,
    d: np.ndarray,
    x: np.ndarray,
) -> float:
    return 0.5 * float(
        np.trapezoid(
            np.sum((u - d) ** 2, axis=0),
            x=x,
        )
    )


def cot_misfit(
    u: np.ndarray,
    d: np.ndarray,
    x: np.ndarray,
    beta: float,
) -> float:
    """
    J_COT =
        1/2 [W2^2(Ru_x,Rd_x) + W2^2(Ru_z,Rd_z)].
    """
    J = 0.0

    for k in range(2):
        uk = u[k, :, None]
        dk = d[k, :, None]

        Jk, _ = get_ot_derivative(
            x,
            uk,
            dk,
            type="softplus",
            beta=beta,
        )

        J += 0.5 * float(Jk)

    return J


def rot_misfit(
    u: np.ndarray,
    d: np.ndarray,
    x: np.ndarray,
    beta: float,
    lam: float,
) -> float:
    """
    ROT using the original ROT_corrected.py implementation.
    """
    u3 = u[:, :, None]
    d3 = d[:, :, None]

    J, _ = ot_dist_equalize_multitrace_with_grad_softplus_encoding(
        x,
        u3,
        d3,
        alpha=lam,
        beta=beta,
    )

    return float(J)


# ============================================================
# Landscape computation
# ============================================================

def compute_landscapes() -> dict:
    x = np.arange(
        0.0,
        T_MAX + 0.5 * DT,
        DT,
        dtype=np.float64,
    )

    u = build_reference_signal(x)

    taus = np.linspace(
        TAU_MIN,
        TAU_MAX,
        N_TAU,
    )

    phis = np.linspace(
        PHI_MIN,
        PHI_MAX,
        N_PHI,
    )

    shape = (N_PHI, N_TAU)

    J_l2 = np.empty(shape, dtype=np.float64)
    J_cot = np.empty(shape, dtype=np.float64)
    J_rot = np.empty(shape, dtype=np.float64)

    total = N_PHI * N_TAU
    done = 0
    report_step = max(total // 20, 1)

    for ip, phi in enumerate(phis):
        for it, tau in enumerate(taus):
            d = transform_signal(
                u,
                x,
                tau,
                phi,
            )

            J_l2[ip, it] = l2_misfit(
                u,
                d,
                x,
            )

            J_cot[ip, it] = cot_misfit(
                u,
                d,
                x,
                beta=BETA_COT,
            )

            J_rot[ip, it] = rot_misfit(
                u,
                d,
                x,
                beta=BETA_ROT,
                lam=LAMBDA_ROT,
            )

            done += 1
            if done % report_step == 0 or done == total:
                print(
                    f"[landscape] "
                    f"{100.0 * done / total:6.1f}%"
                )

    TAU, PHI = np.meshgrid(
        taus,
        phis,
    )

    J_rot_ideal = (
        TAU**2
        + 4.0
        * LAMBDA_ROT
        * (1.0 - np.cos(PHI))
    )

    return {
        "x": x,
        "u": u,
        "taus": taus,
        "phis": phis,
        "J_l2": J_l2,
        "J_cot": J_cot,
        "J_rot": J_rot,
        "J_rot_ideal": J_rot_ideal,
    }


# ============================================================
# Utilities
# ============================================================

def normalize01(A: np.ndarray) -> np.ndarray:
    """Independently normalize one full 2D landscape to [0,1]."""
    amin = float(np.min(A))
    amax = float(np.max(A))

    if np.isclose(amax, amin):
        return np.zeros_like(A)

    return (A - amin) / (amax - amin)


def nearest_index(
    x: np.ndarray,
    value: float,
) -> int:
    return int(np.argmin(np.abs(x - value)))


def add_panel_label(
    ax,
    label: str,
    x: float = 0.025,
    y: float = 0.965,
):
    """
    Panel label with regular font weight, matching the manuscript.
    """
    ax.text(
        x,
        y,
        label,
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=PANEL_FONTSIZE,
        fontweight=PANEL_FONTWEIGHT,
    )


def set_standard_angle_ticks(
    ax,
    axis: str = "y",
):
    ticks = np.array(
        [
            -np.pi / 2.0,
            -np.pi / 4.0,
            0.0,
            np.pi / 4.0,
            np.pi / 2.0,
        ]
    )

    labels = [
        r"$-\pi/2$",
        r"$-\pi/4$",
        r"$0$",
        r"$\pi/4$",
        r"$\pi/2$",
    ]

    if axis == "y":
        ax.set_yticks(ticks)
        ax.set_yticklabels(labels)
    elif axis == "x":
        ax.set_xticks(ticks)
        ax.set_xticklabels(labels)
    else:
        raise ValueError("axis must be 'x' or 'y'")


