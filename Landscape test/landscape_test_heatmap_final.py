def print_diagnostics(res: dict):
    print("\n" + "=" * 76)
    print("Landscape diagnostics")
    print("=" * 76)

    for key, label in [
        ("J_l2", "L2"),
        ("J_cot", "COT"),
        ("J_rot", "ROT"),
    ]:
        A = res[key]

        ip, it = np.unravel_index(
            np.argmin(A),
            A.shape,
        )

        print(
            f"{label:4s}: "
            f"min={A[ip, it]:.8e}, "
            f"tau={res['taus'][it]:+.6f} s, "
            f"phi={res['phis'][ip]:+.6f} rad"
        )


