        J_cot=res["J_cot"],
        J_rot=res["J_rot"],
        J_rot_ideal=res["J_rot_ideal"],
        beta_cot=BETA_COT,
        beta_rot=BETA_ROT,
        lambda_rot=LAMBDA_ROT,
        dt=DT,
        f0=F0,
