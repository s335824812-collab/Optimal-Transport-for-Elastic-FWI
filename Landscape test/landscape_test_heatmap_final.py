"""
Final paper-ready landscape test for L2, COT, and ROT.

Required files in the same directory:
    - Wd1d_optimized.py
    - ROT_corrected.py

Controlled transformation:
    d_{tau,phi}(t) = Q_phi u(t - tau)

Angular convention:
    - All angular variables are in radians.
    - Landscape range: phi in [-pi/2, pi/2].
    - Reference polarization: theta0 = pi/6.
    - 3D example rotation: phi = pi/4.

Outputs
-------
Landscape_Test_Final/
    figure_3d_example.png
    figure_landscape_comparison.png
    figure_landscape_slices.png
    landscape_results.npz

Notes
-----
1. Each L2/COT/ROT landscape is independently normalized to [0,1]
   for visualization.
2. Panel labels use regular font weight (not bold), matching the
   manuscript's current figure-label style.
3. If RECOMPUTE=False, an existing NPZ generated by an earlier
   degree-based version can also be reused: phis_deg is converted
   to radians automatically.
"""

